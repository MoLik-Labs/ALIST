import assert from 'node:assert/strict';
import worker, { targetUrl, sample, summarize } from '../deploy/uptime-monitor/worker.mjs';

const now = Date.now();
assert.equal(targetUrl('https://example.onrender.com'), 'https://example.onrender.com/ping');
for (const url of ['http://example.onrender.com', 'https://example.onrender.com/', 'https://example.onrender.com@evil.test', 'https://example.onrender.com.evil.test', 'https://127.0.0.1', 'https://example.onrender.com:443', 'https://example.onrender.com?x=1', 'https://-x.onrender.com']) assert.equal(targetUrl(url), null);
let stored = null;
const calls = [];
const env = { RENDER_ORIGIN: 'https://example.onrender.com', MONITOR_KV: { async get() { return stored && JSON.parse(stored); }, async put(key, value) { assert.equal(key, 'samples'); stored = value; } } };
await sample(env, now - 1000, async (url, init) => { calls.push({ url, init }); return new Response('pong'); });
assert.equal(calls[0].url, 'https://example.onrender.com/ping');
assert.equal(calls[0].init.redirect, 'manual');
assert.deepEqual(summarize(JSON.parse(stored), now).state, 'up');
await sample(env, now, async () => new Response('not pong', { status: 200 }));
let summary = summarize(JSON.parse(stored), now);
assert.deepEqual([summary.state, summary.successful, summary.samples], ['down', 1, 2]);
assert.equal(summarize(JSON.parse(stored), now + 16 * 60 * 1000).state, 'stale');
await sample(env, now + 1, async () => new Response(null, { status: 302, headers: { location: 'http://127.0.0.1' } }));
assert.equal(JSON.parse(stored).at(-1).up, false);
await sample(env, now + 2, async () => new Response('x'.repeat(1000)));
assert.equal(JSON.parse(stored).at(-1).up, false);
const latest = stored;
await sample(env, now, async () => new Response('pong'));
assert.equal(stored, latest, 'delayed scheduled event must not overwrite newer samples');
await assert.rejects(sample({ ...env, RENDER_ORIGIN: 'https://evil.test' }, now, async () => { throw new Error('must not call'); }));
let result = await worker.fetch(new Request('https://status.test/api/status'), env);
assert.equal(result.status, 200);
const data = await result.json();
assert.equal(JSON.stringify(data).includes('example.onrender.com'), false);
assert.equal(result.headers.get('cache-control'), 'no-store');
assert.equal((await worker.fetch(new Request('https://status.test/?url=https://evil.test'), env)).status, 200);
assert.equal((await worker.fetch(new Request('https://status.test/api/status', { method: 'POST' }), env)).status, 405);
assert.equal((await worker.fetch(new Request('https://status.test/api/status'), { MONITOR_KV: { get: async () => { throw new Error('secret'); } } })).status, 503);
assert.equal(summarize([], now).state, 'unknown');
assert.equal(summarize([{ t: now + 1000, up: true, ms: 1 }], now).state, 'unknown');
console.log('Independent uptime monitor target, scheduler, failure, history and public endpoint tests passed');
